#!/usr/bin/env python3
"""Build the English (/) and Italian (/it/) home pages from _src/home.bilingual.html.

Edit the bilingual source (elements with class "en"/"en-block" and "it"/"it-block"),
then run:  python3 _tools/build_home.py
Folders starting with "_" are not published by GitHub Pages (Jekyll).
"""
import pathlib
from bs4 import BeautifulSoup, Comment

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "_src" / "home.bilingual.html"
SITE = "https://vantagefinanceandtech.com"

HEAD = {
    "en": {
        "title": "Vantage Finance & Tech | SAP S/4HANA Finance, Oracle ERP Cloud & PMO Consulting",
        "description": "SAP S/4HANA Finance and Oracle Cloud ERP consulting for international groups, based in Turin: IFRS 18, treasury and cash management, e-invoicing, finance data and PMO. Ex Deloitte and PwC.",
        "url": SITE + "/", "locale": "en_GB", "alt_locale": "it_IT",
    },
    "it": {
        "title": "Vantage Finance & Tech | Consulenza SAP S/4HANA Finance, Oracle Cloud ERP e PMO",
        "description": "Consulenza SAP S/4HANA Finance e Oracle Cloud ERP per gruppi internazionali, da Torino: IFRS 18, tesoreria e cash management, fatturazione elettronica, dati finance e PMO. Ex Deloitte e PwC.",
        "url": SITE + "/it/", "locale": "it_IT", "alt_locale": "en_GB",
    },
}

# Guides that have an Italian version: the Italian home links to it.
IT_GUIDES = {
    "/guides/sap-vim-vendor-invoice-management/": "/guides/sap-vim-architettura-funzionale/",
    "/guides/ifrs-18-sap-s4hana/": "/guides/ifrs-18-sap-s4hana-guida/",
    "/guides/e-invoicing-sap-s4hana-oracle-fusion/": "/guides/fatturazione-elettronica-sap-s4hana-oracle-fusion/",
    "/guides/erp-trends-cfo-2027-2030/": "/guides/tendenze-erp-cfo-2027-2030/",
    "/guides/sap-s4hana-localization-europe/": "/guides/localizzazione-sap-s4hana-europa/",
    "/guides/sap-ecc-end-of-support-2027/": "/guides/sap-ecc-fine-manutenzione-2027/",
    "/guides/vida-e-invoicing-2030/": "/guides/vida-fatturazione-elettronica-2030/",
}

LANG_SWITCH = ('<a class="lang-btn{en_active}" href="/" id="btn-en" hreflang="en" lang="en">EN</a>\n'
               '    <a class="lang-btn{it_active}" href="/it/" id="btn-it" hreflang="it" lang="it">IT</a>')


def build(lang: str) -> str:
    other = "it" if lang == "en" else "en"
    soup = BeautifulSoup(SRC.read_text(encoding="utf-8"), "html.parser")

    # Keep only this language's text.
    for el in soup.find_all(class_=True):
        if el.decomposed:
            continue
        classes = el.get("class", [])
        if other in classes or f"{other}-block" in classes:
            el.decompose()

    html = soup.find("html")
    html["lang"] = lang
    if lang == "it":
        html["class"] = "lang-it"
    elif "class" in html.attrs:
        del html["class"]

    h = HEAD[lang]
    soup.title.string = h["title"]
    soup.find("meta", attrs={"name": "description"})["content"] = h["description"]
    soup.find("meta", attrs={"property": "og:title"})["content"] = h["title"]
    soup.find("meta", attrs={"property": "og:description"})["content"] = h["description"]
    soup.find("meta", attrs={"property": "og:url"})["content"] = h["url"]
    soup.find("meta", attrs={"property": "og:locale"})["content"] = h["locale"]
    soup.find("meta", attrs={"property": "og:locale:alternate"})["content"] = h["alt_locale"]
    canonical = soup.find("link", attrs={"rel": "canonical"})
    canonical["href"] = h["url"]
    for old in soup.find_all("link", attrs={"rel": "alternate", "hreflang": True}):
        old.decompose()
    for code, href in (("en", SITE + "/"), ("it", SITE + "/it/"), ("x-default", SITE + "/")):
        tag = soup.new_tag("link", rel="alternate", hreflang=code, href=href)
        canonical.insert_after(tag)
        canonical.insert_after("\n")

    if lang == "it":
        for a in soup.find_all("a", href=True):
            if a["href"] in IT_GUIDES:
                a["href"] = IT_GUIDES[a["href"]]
        # Avoid two identical links where the source offered EN + IT versions side by side.
        for p in soup.find_all("p", class_="card-links"):
            seen = set()
            for a in p.find_all("a", href=True):
                href = a["href"]
                if href in seen:
                    a.decompose()
                else:
                    seen.add(href)

    # Language buttons become links between the two pages.
    switcher = soup.find("div", class_="lang-switcher")
    for b in switcher.find_all("button"):
        b.decompose()
    switcher.append(BeautifulSoup(LANG_SWITCH.format(
        en_active=" active" if lang == "en" else "",
        it_active=" active" if lang == "it" else ""), "html.parser"))

    for c in soup.find_all(string=lambda t: isinstance(t, Comment) and t.strip().startswith("build:")):
        c.replace_with(Comment(" generated by _tools/build_home.py from _src/home.bilingual.html: edit the source, not this file "))
    return str(soup)


if __name__ == "__main__":
    (ROOT / "index.html").write_text(build("en"), encoding="utf-8")
    (ROOT / "it").mkdir(exist_ok=True)
    (ROOT / "it" / "index.html").write_text(build("it"), encoding="utf-8")
    print("built index.html and it/index.html")
